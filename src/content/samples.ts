export const SLIDE_ATTENTION = `# ステップ2
# 文脈を読む仕組み

---

## 同じことばでも意味がちがう

- 「昨日は **はし** を渡った」
- 「ごはんを **はし** で食べた」

同じ「はし」でも意味が正反対。

どうやって見分けている？

---

## 答え：まわりのことばを見ている

**「渡った」があるから → 橋**
**「ごはん」があるから → 箸**

人間が自然にやっているこの作業を、
AIは **アテンション（注意）** という仕組みで行います。

---

## アテンションのイメージ

文の中のことば同士が
「キミはどれくらい私に関係ある？」
とお互いに点数をつけあう。

点数の高いことばの情報を強く受け取って、
自分の意味を決めていきます。

---

## だから長い文でもつながる

「太郎は花子に本を貸した。**彼女**はそれを読んだ。」

→ 「彼女」が「花子」を強く見ている
→ 「それ」が「本」を強く見ている

この点数計算を何十層も積み重ねたものが
**Transformer（トランスフォーマー）** という構造です。
`;

